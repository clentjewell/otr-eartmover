/**
 * OTR Earthmover Tyre, Knowledge Portal ASK endpoint (Supabase backend).
 *
 * POST { q: string }
 *
 * Pipeline (mirrors worker/api/ask.js, same response contract):
 *   Pricing guard, commercial questions decline and escalate to David,
 *     checked BEFORE Track A so "how much does a 40.00R57 cost?" never
 *     dumps that size's spec records.
 *   Track A, numeric spec questions (a size, or a TRA code + value word) are
 *     answered by exact lookup in kb_specs (verified rows only, rendered as a
 *     spec table) or ABSTAIN. They never reach retrieval or a language model.
 *     Comparative/recommendation questions ("26.5R25 alternatives to
 *     Bridgestone") are excluded, they want a discussion, not a spec table.
 *   Track B, embed the question (gte-small, built into the edge runtime),
 *     hybrid match over kb_chunks (vector + keyword), then:
 *       • extractive mode (default, no key needed): verbatim passages + citations
 *       • generative mode (ANTHROPIC_API_KEY secret set): plain-language summary
 *         + up to 3 RELATED follow-up questions via the sentinel format
 *   Fallback, nothing relevant: labelled general guidance via Claude if a key
 *     is set, else an honest "not in my sources".
 *
 * RESPONSE CONTRACT (guardrail, see ../../ask.html renderApiAnswer/renderAnswer):
 *   Every path below returns the same four fields, always populated, so the
 *   front end can render Question / Answer / Opinion / Sources in a fixed
 *   order with no branch-specific layout:
 *     - lede:       one-sentence headline answer
 *     - answer:     HTML, the factual/descriptive content (table, prose, or
 *                   verbatim excerpts). Never a recommendation or call to action.
 *     - suggestion: HTML, the actionable next step: what to do, what to check,
 *                   who to call, or a caveat. NEVER blank, every path below
 *                   sets an explicit suggestion, even a generic one. Rendered
 *                   under the "/ OPINION" label on the front end.
 *     - sources:    array (possibly empty) of {num, text, url}
 *   `body` is also set (mirrors `answer`) for older consumers that read the
 *   pre-guardrail contract (e.g. the Cloudflare Pages proxy fallback path).
 *
 * Displayed verbatim excerpts are prose-only in generative mode (an empty
 * quote section beats table debris; the cited answer + source links stand on
 * their own). Extractive mode falls back to raw matches because there the
 * excerpts ARE the answer. Retrieval/LLM context are never filtered.
 */
