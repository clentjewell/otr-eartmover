const SOURCE_FALLBACK = "https://otrearthmovertyres.com/resources.html";

function sourceUrl(s: string, page?: number | null): string {
  let url = SOURCE_FALLBACK;
  for (const [re, u] of SOURCE_LINKS) { if (re.test(s)) { url = u; break; } }
  if (page && /\.pdf$/i.test(url)) url += `#page=${page}`;
  return url;
}

function esc(s: string): string {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// Is a retrieved chunk readable prose, or table/header debris? Display-only.
function isProseExcerpt(t: string): boolean {
  const words = t.trim().split(/\s+/);
  if (words.length < 12) return false;
  const digits = (t.match(/\d/g) || []).length;
  if (digits / t.length > 0.22) return false;
  const norm = words.map((w) => w.toLowerCase().replace(/[^a-z0-9./-]/g, ""));
  if (new Set(norm).size / words.length < 0.5) return false;
  const fn = norm.filter((w) => /^(the|and|of|to|a|is|are|for|with|in|on|be|or|it|that|as|at|by|this|from|not|when|should)$/.test(w)).length;
  if (fn / words.length < 0.06) return false;
  const lower = words.filter((w) => /^[a-z]/.test(w)).length;
  return lower / words.length >= 0.5;
}

// A response with `answer` set is complete per the guardrail contract; `body`
// mirrors `answer` for pre-guardrail consumers. Every return path below MUST
// pass a non-empty `suggestion`.
function contract(parts: {
  lede: string; answer: string; suggestion: string;
  sources?: unknown[]; excerpts?: unknown[]; citations?: unknown[]; related?: string[];
  clarify?: string;
  escalation: boolean; abstained?: boolean; mode?: string;
}) {
  return {
    lede: parts.lede,
    answer: parts.answer,
    body: parts.answer,
    suggestion: parts.suggestion,
    sources: parts.sources ?? [],
    excerpts: parts.excerpts ?? [],
    citations: parts.citations ?? [],
    related: parts.related ?? [],
    clarify: parts.clarify ?? "",
    escalation: parts.escalation,
    abstained: parts.abstained ?? false,
    mode: parts.mode,
    disclaimer: DISCLAIMER,
  };
}

